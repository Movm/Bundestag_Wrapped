import Ajv from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standalone from 'ajv/dist/standalone/index.js';
import { readFileSync, writeFileSync } from 'node:fs';

const schema = JSON.parse(readFileSync(new URL('../src/generated/wrapped-contract-v1.schema.json', import.meta.url), 'utf8'));
const ajv = new Ajv({ allErrors: true, strict: true, code: { source: true, esm: true } });
addFormats(ajv);
ajv.addSchema(schema);
const names = [
  'EditionsIndex', 'EditionManifest', 'EditionContent', 'WrappedData', 'SpeakerIndexAsset',
  'SpeakerWrappedAsset', 'SpeechesAsset', 'WordsAsset', 'WordRankingsAsset', 'TopicRankingsAsset',
];
let code = standalone(ajv, Object.fromEntries(names.map(name => [name, `${schema.$id}#/$defs/${name}`])));
// Ajv standalone emits CommonJS helper references even with esm=true.
// Keep only the small validation helpers; schema compilation stays build-time.
code = code.replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length')
  .replaceAll('require("ajv-formats/dist/formats").fullFormats', 'fullFormats');
if (code.includes('require(')) throw new Error('Unsupported standalone runtime helper');
code = '// GENERATED by scripts/generate-contract-validators.mjs. Do not edit.\n' +
  'import ucs2lengthModule from "ajv/dist/runtime/ucs2length";\nconst ucs2length = ucs2lengthModule.default ?? ucs2lengthModule;\n' +
  'import { fullFormats } from "ajv-formats/dist/formats";\n' + code + '\n';
const declaration = 'import type { ValidateFunction } from "ajv";\n' + names.map(name => `export const ${name}: ValidateFunction;`).join('\n') + '\n';
for (const [file, content] of [['wrapped-contract-validators.js', code], ['wrapped-contract-validators.d.ts', declaration]]) {
  const url = new URL(`../src/generated/${file}`, import.meta.url);
  if (process.argv.includes('--check')) {
    if (readFileSync(url, 'utf8') !== content) throw new Error('Stale contract validators; run pnpm contract:generate');
  } else writeFileSync(url, content);
}
