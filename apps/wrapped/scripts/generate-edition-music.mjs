import { readdirSync, existsSync, readFileSync, writeFileSync } from 'node:fs';

const configDir = new URL('../config/', import.meta.url);
const editions = readdirSync(configDir, { withFileTypes: true })
  .filter(entry => entry.isDirectory() && existsSync(new URL(`${entry.name}/music.json`, configDir)))
  .map(entry => entry.name)
  .sort();

// Static imports with relative paths: Vite and Metro both resolve them, unlike import.meta.glob.
const content = '// GENERATED by scripts/generate-edition-music.mjs. Do not edit.\n' +
  editions.map((id, i) => `import edition${i} from '../../config/${id}/music.json';\n`).join('') +
  '\nexport const EDITION_MUSIC_FILES: Record<string, unknown> = {\n' +
  editions.map((id, i) => `  '${id}': edition${i},\n`).join('') + '};\n';

const url = new URL('../src/generated/edition-music.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (!existsSync(url) || readFileSync(url, 'utf8') !== content) {
    console.error('Stale edition music index; run node scripts/generate-edition-music.mjs');
    process.exit(1);
  }
} else writeFileSync(url, content);
